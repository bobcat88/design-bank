// Builds shared/catalog.js and shared/archetypes.js, and validates archetype tokens against design-studio/studio/build.py.
// Usage: node tools/catalog.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const STUDIO_FONTS = new Set([
  'Hanken Grotesk', 'Geist', 'Instrument Sans', 'Manrope', 'Figtree', 'Plus Jakarta Sans',
  'Sora', 'Bricolage Grotesque', 'DM Sans', 'Outfit', 'Montserrat',
  'Fraunces', 'Newsreader', 'Source Serif 4', 'JetBrains Mono',
]);
const TOKEN_KEYS = ['theme', 'accent', 'warmth', 'tint', 'radius', 'density', 'scale', 'display', 'dweight', 'body', 'motion'];

const strip = (s) =>
  s.replace(/<[^>]+>/g, '')
    .replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ').trim();

// 1. Validate data/archetypes.json against design-studio's strict token schema
const archData = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/archetypes.json'), 'utf8'));
const tokenErrors = [];
for (const a of archData.archetypes) {
  const t = a.tokens || {};
  for (const k of TOKEN_KEYS) if (!(k in t)) tokenErrors.push(`${a.id}: missing token "${k}"`);
  if (!['light', 'dark'].includes(t.theme)) tokenErrors.push(`${a.id}: theme must be light|dark`);
  if (!/^#[0-9a-fA-F]{6}$/.test(String(t.accent || ''))) tokenErrors.push(`${a.id}: invalid accent "${t.accent}"`);
  for (const [k, lo, hi] of [['warmth', -1, 1], ['tint', 0, 6], ['radius', 0, 28], ['density', 0.8, 1.3], ['scale', 1.125, 1.5], ['dweight', 100, 900]]) {
    if (typeof t[k] !== 'number' || t[k] < lo || t[k] > hi) tokenErrors.push(`${a.id}: ${k} (${t[k]}) out of [${lo}, ${hi}]`);
  }
  for (const k of ['display', 'body']) {
    if (!STUDIO_FONTS.has(t[k])) tokenErrors.push(`${a.id}: ${k} "${t[k]}" not in design-studio FONTS`);
  }
  if (!['none', 'subtle', 'lively'].includes(t.motion)) tokenErrors.push(`${a.id}: invalid motion "${t.motion}"`);
  const pagePath = path.join(ROOT, a.page);
  if (!fs.existsSync(pagePath)) tokenErrors.push(`${a.id}: missing page ${a.page}`);
}
if (tokenErrors.length) {
  console.error('Archetype schema validation failed:\n  ' + tokenErrors.join('\n  '));
  process.exit(1);
}

// 2. Build catalog entries from css.html, wow.html, webgl.html
const out = [];
for (const page of ['css', 'wow']) {
  const html = fs.readFileSync(path.join(ROOT, `protos/${page}.html`), 'utf8');
  const metaMatch = html.match(/const META = (\{[\s\S]*?\});/);
  if (!metaMatch) throw new Error(`META not found in protos/${page}.html`);
  const meta = new Function('return (' + metaMatch[1] + ')')();
  let section = '';
  for (const m of html.matchAll(/<h2>(.*?)<\/h2>|<article id="(\w+)"[^>]*><h3>(.*?)<\/h3><p>(.*?)<\/p>([\s\S]*?)<\/article>/g)) {
    if (m[1]) { section = strip(m[1]); continue; }
    const [w, p] = meta[m[2]] || [0, 'wdm'];
    const code = (m[5].match(/<(style|script type="x-shader[^"]*")>([\s\S]*?)<\/(style|script)>/) || [])[2] || '';
    out.push([page, m[2], strip(m[3]), strip(m[4]), w, p, section, code.replace(/^\n|\s+$/g, '')]);
  }
}

// Evaluate shared/shader.js in a minimal stub to extract string GLSL bodies (including { lib, main } objects)
const win = { Bank: {}, addEventListener: () => {} };
new Function('window', 'Bank', 'document', fs.readFileSync(path.join(ROOT, 'shared/shader.js'), 'utf8'))(win, win.Bank, { addEventListener: () => {} });
const SHADER_META = {
  aurora: [5, 'wdm'], chrome: [5, 'wd'], contours: [4, 'wdm'], mesh: [4, 'wdm'],
  orb: [5, 'wd'], rays: [5, 'wd'], globe: [5, 'wd'], dotwave: [4, 'wd'],
  ascii: [4, 'wd'], flow: [5, 'wdm'], reveal: [5, 'wd'], foil: [5, 'wd'],
  particles: [4, 'wd'], waves: [4, 'wd'], ripple: [4, 'wdm'], lava: [4, 'wdm'],
};
for (const m of fs.readFileSync(path.join(ROOT, 'protos/webgl.html'), 'utf8').matchAll(/<section class="case[^"]*" id="(\w+)" data-shader="(\w+)">[\s\S]*?<h2>(.*?)<\/h2><p>(.*?)<\/p>/g)) {
  const [w, p] = SHADER_META[m[2]] || [5, 'wd'];
  const code = win.Bank.shaderCode ? win.Bank.shaderCode(m[2]) : String(win.Bank.SHADERS[m[2]] || '');
  out.push(['webgl', m[1], strip(m[3]), strip(m[4]), w, p, 'Shaders', code]);
}

const catalogText =
  '/* generated by tools/catalog.mjs from css.html, wow.html, webgl.html: [page, id, title, blurb, wow, platforms, section, code] */\n' +
  'window.CATALOG = ' + JSON.stringify(out).replace(/\],\[/g, '],\n[') + ';\n';

const archetypesText =
  '/* generated by tools/catalog.mjs from data/archetypes.json (classic script mirror for file://) */\n' +
  'window.ARCHETYPES_DATA = ' + JSON.stringify(archData, null, 2) + ';\n';

const files = [
  [path.join(ROOT, 'shared/catalog.js'), catalogText],
  [path.join(ROOT, 'shared/archetypes.js'), archetypesText],
];

if (CHECK) {
  let stale = false;
  for (const [fp, expected] of files) {
    const actual = fs.existsSync(fp) ? fs.readFileSync(fp, 'utf8') : '';
    if (actual !== expected) {
      console.error(`STALE: ${path.relative(ROOT, fp)} (run "node tools/catalog.mjs")`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log(`OK: ${out.length} catalog entries, ${archData.archetypes.length} validated archetypes.`);
} else {
  for (const [fp, content] of files) fs.writeFileSync(fp, content, 'utf8');
  console.log(`Wrote ${out.length} catalog entries + ${archData.archetypes.length} archetypes.`);
}
