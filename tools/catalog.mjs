// Builds design-bank/shared/catalog.js from the catalogue pages: [page, id, title, blurb, wow, platforms, section]
import fs from 'node:fs';
const root = 'D:/Projets/design-bank/', out = [];
const strip = (s) => s.replace(/<[^>]+>/g, '').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
for (const page of ['css', 'wow']) {
  const html = fs.readFileSync(`${root}protos/${page}.html`, 'utf8');
  const meta = eval('(' + html.match(/const META = (\{[\s\S]*?\});/)[1] + ')');
  let section = '';
  for (const m of html.matchAll(/<h2>(.*?)<\/h2>|<article id="(\w+)"[^>]*><h3>(.*?)<\/h3><p>(.*?)<\/p>([\s\S]*?)<\/article>/g)) {
    if (m[1]) { section = strip(m[1]); continue; }
    const [w, p] = meta[m[2]] || [0, 'wdm'];
    const code = (m[5].match(/<(style|script type="x-shader[^"]*")>([\s\S]*?)<\/(style|script)>/) || [])[2] || '';
    out.push([page, m[2], strip(m[3]), strip(m[4]), w, p, section, code.replace(/^\n|\s+$/g, '')]);
  }
}
// shader bodies: evaluate shader.js's SHADERS map with a stub window
const win = { Bank: {} }; new Function('window', 'Bank', 'document', fs.readFileSync(`${root}shared/shader.js`, 'utf8'))(win, win.Bank, {}); // our own file
for (const m of fs.readFileSync(`${root}protos/webgl.html`, 'utf8').matchAll(/<section class="case[^"]*" id="(\w+)" data-shader="(\w+)">[\s\S]*?<h2>(.*?)<\/h2><p>(.*?)<\/p>/g))
  out.push(['webgl', m[1], strip(m[3]), strip(m[4]), 5, 'wd', 'Shaders', win.Bank.SHADERS[m[2]]]);
fs.writeFileSync(`${root}shared/catalog.js`, '/* generated by catalog.mjs from css.html, wow.html, webgl.html: [page, id, title, blurb, wow, platforms, section] */\nwindow.CATALOG = ' + JSON.stringify(out).replace(/\],\[/g, '],\n[') + ';\n');
console.log(out.length, 'entries');
